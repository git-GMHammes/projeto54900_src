import type { Attr } from './atributosFill';

export interface ServiceItem {
  name: string;
  type: string;
  provider: 'biscate' | 'mei' | 'company';
  billingUnit: string;
  price: number;
  /** [valor, unidade de tempo]: duracao estimada e prazo para iniciar (min, h, d, wk, mo). */
  duration: [number, 'min' | 'h' | 'd' | 'wk' | 'mo'];
  lead: [number, 'min' | 'h' | 'd' | 'wk' | 'mo'];
  description: string;
  attrs: readonly Attr[];
}

/** Especificacao "de bancada" de um servico; `svc` monta a lista de caracteristicas do catalogo. */
interface ServiceSpec {
  name: string;
  type: string;
  provider: ServiceItem['provider'];
  billingUnit: string;
  price: number;
  duration: ServiceItem['duration'];
  lead: ServiceItem['lead'];
  description: string;
  aliases: string[];
  area: string;
  categories: string[];
  tags: string[];
  cbo?: string;
  cnae?: string;
  lc116?: string;
  externalCode: string;
  mode: 'presencial' | 'remoto' | 'hibrido';
  place: 'cliente' | 'prestador' | 'terceiro';
  team: number;
  equipment: string[];
  material: boolean;
  travel: boolean;
  radiusKm: number;
  minQuantity?: [string, string];
  days: ('seg' | 'ter' | 'qua' | 'qui' | 'sex' | 'sab' | 'dom')[];
  start: string;
  end: string;
  noticeHours: number;
  quoteDays: number;
  warrantyMonths: number;
  urgent: boolean;
  minPrice: number;
  visitFee: number;
  urgentFeePct: number;
  maxDiscountPct: number;
  payments: ('pix' | 'dinheiro' | 'cartao' | 'boleto' | 'transferencia')[];
  maxInstallments: number;
  regime: 'autonomo' | 'mei' | 'simples' | 'presumido' | 'real';
  invoice: boolean;
  issPct: string;
  city: string;
  registrations: string[];
  habilitations: string[];
  insurance: boolean;
  background: boolean;
  epi: string[];
  risk: 'baixo' | 'medio' | 'alto' | 'critico';
  restrictions: string[];
  licenses: string[];
  norms: string[];
  specs: [string, string, string?][];
}

function svc(s: ServiceSpec): ServiceItem {
  const bool = (v: boolean): string => (v ? 'true' : 'false');
  const attrs: Attr[] = [
    ...s.aliases.map((a): Attr => ['identificacao', 'apelido', a, { multi: true }]),
    ['identificacao', 'codigo_externo', s.externalCode],
    ['classificacao', 'area', s.area],
    ...s.categories.map((c): Attr => ['classificacao', 'categoria', c, { multi: true }]),
    ...(s.cbo ? ([['classificacao', 'cbo', s.cbo]] as Attr[]) : []),
    ...(s.cnae ? ([['classificacao', 'cnae', s.cnae]] as Attr[]) : []),
    ...(s.lc116 ? ([['classificacao', 'lc116', s.lc116]] as Attr[]) : []),
    ...s.tags.map((t): Attr => ['classificacao', 'etiqueta', t, { multi: true }]),
    ['execucao', 'modalidade', s.mode],
    ['execucao', 'local_execucao', s.place],
    ['execucao', 'equipe', String(s.team)],
    ...s.equipment.map((e): Attr => ['execucao', 'equipamento', e, { multi: true }]),
    ['execucao', 'material_incluso', bool(s.material)],
    ['execucao', 'deslocamento_incluso', bool(s.travel)],
    ['execucao', 'raio_atendimento', String(s.radiusKm), { unit: 'km' }],
    ...(s.minQuantity ? ([['execucao', 'quantidade_minima', s.minQuantity[0], { unit: s.minQuantity[1] }]] as Attr[]) : []),
    ...s.days.map((d): Attr => ['agenda', 'dia_atendimento', d, { multi: true }]),
    ['agenda', 'horario_inicio', s.start],
    ['agenda', 'horario_fim', s.end],
    ['agenda', 'antecedencia_minima', String(s.noticeHours), { unit: 'h' }],
    ['agenda', 'validade_orcamento', String(s.quoteDays), { unit: 'd' }],
    ['agenda', 'garantia', String(s.warrantyMonths), { unit: 'mo' }],
    ['agenda', 'urgencia', bool(s.urgent)],
    ['preco', 'preco_minimo', s.minPrice.toFixed(2)],
    ['preco', 'taxa_visita', s.visitFee.toFixed(2)],
    ['preco', 'taxa_urgencia', String(s.urgentFeePct), { unit: '%' }],
    ['preco', 'desconto_maximo', String(s.maxDiscountPct), { unit: '%' }],
    ...s.payments.map((p): Attr => ['preco', 'forma_pagamento', p, { multi: true }]),
    ['preco', 'parcelamento_maximo', String(s.maxInstallments)],
    ['fiscal', 'regime_tributario', s.regime],
    ['fiscal', 'emite_nota', bool(s.invoice)],
    ['fiscal', 'iss_aliquota', s.issPct, { unit: '%' }],
    ['fiscal', 'municipio_tributacao', s.city],
    ...s.registrations.map((r): Attr => ['exigencias', 'registro_profissional', r, { multi: true }]),
    ...s.habilitations.map((h): Attr => ['exigencias', 'habilitacao', h, { multi: true }]),
    ['exigencias', 'seguro', bool(s.insurance)],
    ['exigencias', 'antecedentes', bool(s.background)],
    ...s.epi.map((e): Attr => ['exigencias', 'epi', e, { multi: true }]),
    ['seguranca', 'nivel_risco', s.risk],
    ...s.restrictions.map((r): Attr => ['seguranca', 'restricao_uso', r, { multi: true }]),
    ...s.licenses.map((l): Attr => ['seguranca', 'licenca', l, { multi: true }]),
    ...s.norms.map((n): Attr => ['seguranca', 'norma', n, { multi: true }]),
    ...s.specs.map(([label, value, unit]): Attr => ['especificacao', 'especificacao', value, { label, multi: true, ...(unit ? { unit } : {}) }]),
  ];
  return { name: s.name, type: s.type, provider: s.provider, billingUnit: s.billingUnit, price: s.price, duration: s.duration, lead: s.lead, description: s.description, attrs };
}

